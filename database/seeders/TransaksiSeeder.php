    private function createTransaksi($client, $type, $amount, $kategoriId, $userId, $tanggal)
    {
        $date = \Carbon\Carbon::parse($tanggal)->format('Ymd');
        $prefix = ($type == 'Piutang') ? "INV-$date-BON-" : "INV-$date-UTG-";
        $inv = "INV-$date-AWL-";
        $str = Str::upper(Str::random(4));
        $beda1 = ($type == 'Piutang') ? 'Debit' : 'Kredit';
        $beda2 = ($type == 'Piutang') ? 'Kredit' : 'Debit';


        $kate = Kategori::where('name', 'like', 'Modal Awal')->first();

        $transaksi = Transaksi::create([
            'invoice'   => $prefix . $str,
            'name'      => "$type " . $client->name,
            'user_id'   => $userId,
            'tanggal'   => $tanggal,
            'client_id' => $client->id,
            'type'      => $beda1,
            'total'     => $amount,
        ]);

        DetailTransaksi::create([
            'transaksi_id' => $transaksi->id,
            'kategori_id'  => $kategoriId,
            'kuantitas'    => null,
            'value'        => null,
            'sub_total'    => $amount,
        ]);

        $awal = Transaksi::create([
            'invoice'   => $inv . $str,
            'name'      => "Saldo Awal " . $client->name,
            'user_id'   => $userId,
            'tanggal'   => $tanggal,
            'client_id' => $client->id,
            'type'      => $beda2,
            'total'     => $amount,
        ]);

        DetailTransaksi::create([
            'transaksi_id' => $awal->id,
            'kategori_id'  => $kate->id,
            'kuantitas'    => null,
            'value'        => null,
            'sub_total'    => $amount,
        ]);
    }
